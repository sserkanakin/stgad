"""one fact sheet for the experiments chapter, built straight from the eval jsons.

everything the rewritten chapter 5 quotes comes out of here, so every number in
the draft traces to a file on disk. writes results/analysis/ch5_facts.md.

test numbers are the locked protocol (best_crps ckpt, ancestral 50 steps, k=100,
y==0 masked); anything that only has training-time evals is reported as val and
labelled as such.
"""
import json
import re
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2] / "results"
OUT = ROOT / "analysis" / "ch5_facts.md"

DS = ["pems08f", "pems08s", "pems04f", "pems04s", "metrla", "pemsbay"]
BB = ["mlp", "gcn", "gwn"]
METRICS = ["crps", "mae", "rmse", "coverage", "winkler", "energy", "w1"]

# arm dir -> (prior label, conditioning)
ARMS = {
    "iso": ("iso", "fo"), "iso-past": ("iso", "past"),
    "emp": ("emp", "fo"), "emp-past": ("emp", "past"),
    "rsh": ("rsh", "fo"), "rsh-past": ("rsh", "past"),
    "emp_w": ("emp_w", "fo"), "rsh_w": ("rsh_w", "fo"),
}


def read(p):
    """some runs left zero-byte json behind when the cluster killed them."""
    try:
        return json.loads(p.read_text())
    except (ValueError, OSError):
        return None


def load_test(campaign, arm):
    """seed-keyed test metrics for every (ds, bb) cell of one arm directory."""
    out = defaultdict(dict)
    base = ROOT / campaign / arm
    for p in base.glob("*/*/*/seed*/eval/test_metrics_bestcrps_ancestral50.json"):
        ds, bb, _prior, seed = p.parts[-6], p.parts[-5], p.parts[-4], p.parts[-3]
        d = read(p)
        if d:
            out[(ds, bb)][seed] = d
    return out


def load_recal(campaign, arm):
    out = defaultdict(dict)
    base = ROOT / campaign / arm
    for p in base.glob("*/*/*/seed*/eval/test_metrics_bestcrps_ancestral50_srecal.json"):
        ds, bb, seed = p.parts[-6], p.parts[-5], p.parts[-3]
        d = read(p)
        if d:
            out[(ds, bb)][seed] = d
    return out


def load_val(campaign, arm):
    """best sampled-CRPS on validation + the epoch it was reached."""
    out = defaultdict(dict)
    base = ROOT / campaign / arm
    for p in base.glob("*/*/*/seed*/train/validation_history.json"):
        ds, bb, seed = p.parts[-6], p.parts[-5], p.parts[-3]
        d = read(p)
        if not d:
            continue
        out[(ds, bb)][seed] = {
            "crps": d.get("best_crps"),
            "epoch": d.get("best_crps_epoch"),
            "n_epochs": len(d.get("history", [])),
        }
    return out


def agg(cells, metric):
    """seed mean/std/count per cell."""
    out = {}
    for key, seeds in cells.items():
        v = [s[metric] for s in seeds.values() if s.get(metric) is not None]
        if v:
            out[key] = (float(np.mean(v)), float(np.std(v)), len(v))
    return out


def paired(a, b, metric):
    """per-seed pairing on the seeds both arms have: (n_seeds, wins_for_b)."""
    n = w = 0
    for key in set(a) & set(b):
        for s in set(a[key]) & set(b[key]):
            n += 1
            w += int(b[key][s][metric] < a[key][s][metric])
    return n, w


def fmt(x, d=4):
    return "—" if x is None else f"{x:.{d}f}"


lines = ["# Chapter 5 fact sheet (generated by scripts/analysis/ch5_facts.py)", ""]
L = lines.append

# ---------------------------------------------------------------- test grid
T = {a: load_test("20260721_ladder", a) for a in ARMS}
heat = {}
for arm in ["cart", "cart-past", "cartL", "cartL-past", "cartL3-past", "cartLg2-past"]:
    heat[arm] = load_test("20260724_heat", arm)

L("## 1. Locked-protocol test grid (uncalibrated, seed mean ± std, n seeds)")
for cond in ["fo", "past"]:
    for metric in METRICS:
        L("")
        L(f"### cond={cond} · {metric}")
        L("| ds | bb | iso | emp | rsh | Δ emp vs iso (%) |")
        L("|---|---|--|--|--|--:|")
        for ds in DS:
            for bb in BB:
                row = []
                vals = {}
                for pri in ["iso", "emp", "rsh"]:
                    arm = pri if cond == "fo" else f"{pri}-past"
                    a = agg(T[arm], metric).get((ds, bb))
                    vals[pri] = a[0] if a else None
                    row.append(f"{a[0]:.4f}±{a[1]:.4f}<sub>{a[2]}</sub>" if a else "—")
                if vals["iso"] and vals["emp"]:
                    d = 100.0 * (vals["iso"] - vals["emp"]) / vals["iso"]
                    row.append(f"{d:+.2f}")
                else:
                    row.append("—")
                L(f"| {ds} | {bb} | " + " | ".join(row) + " |")

# ------------------------------------------------- conditioning as a channel
L("")
L("## 2. Conditioning axis: what history conditioning does (test CRPS)")
L("| ds | bb | iso fo | iso past | iso gain % | emp fo | emp past | prior gain fo % | prior gain past % |")
L("|---|---|--|--|--:|--|--|--:|--:|")
for ds in DS:
    for bb in BB:
        i_fo = agg(T["iso"], "crps").get((ds, bb))
        i_pa = agg(T["iso-past"], "crps").get((ds, bb))
        e_fo = agg(T["emp"], "crps").get((ds, bb))
        e_pa = agg(T["emp-past"], "crps").get((ds, bb))
        if not (i_fo and i_pa):
            continue
        gain = 100 * (i_fo[0] - i_pa[0]) / i_fo[0]
        pfo = 100 * (i_fo[0] - e_fo[0]) / i_fo[0] if e_fo else None
        ppa = 100 * (i_pa[0] - e_pa[0]) / i_pa[0] if e_pa else None
        L(f"| {ds} | {bb} | {fmt(i_fo[0])} | {fmt(i_pa[0])} | {gain:+.1f} | "
          f"{fmt(e_fo[0] if e_fo else None)} | {fmt(e_pa[0] if e_pa else None)} | "
          f"{'—' if pfo is None else f'{pfo:+.1f}'} | {'—' if ppa is None else f'{ppa:+.1f}'} |")

# ------------------------------------------------------------ paired seeds
L("")
L("## 3. Paired-seed counts (emp vs iso, all cells pooled)")
for cond in ["fo", "past"]:
    ia, ea = ("iso", "emp") if cond == "fo" else ("iso-past", "emp-past")
    for metric in ["crps", "mae", "rmse", "energy"]:
        n, w = paired(T[ia], T[ea], metric)
        L(f"- cond={cond} {metric}: emp better in {w}/{n} paired seeds")

# --------------------------------------------------------------- heat arm
L("")
L("## 4. Heat (Cartesian product-graph) arm, test CRPS")
L("| ds | bb | iso-past | emp-past | cart-past | cartL-past | cart-fo | iso-fo |")
L("|---|---|--|--|--|--|--|--|")
for ds in DS:
    for bb in BB:
        cells = [agg(T["iso-past"], "crps").get((ds, bb)),
                 agg(T["emp-past"], "crps").get((ds, bb)),
                 agg(heat["cart-past"], "crps").get((ds, bb)),
                 agg(heat["cartL-past"], "crps").get((ds, bb)),
                 agg(heat["cart"], "crps").get((ds, bb)),
                 agg(T["iso"], "crps").get((ds, bb))]
        if not any(cells):
            continue
        L(f"| {ds} | {bb} | " + " | ".join(
            f"{c[0]:.4f}<sub>{c[2]}</sub>" if c else "—" for c in cells) + " |")

# ------------------------------------------------------------ recalibration
L("")
L("## 5. Spread recalibration (emprefit campaign, test, seed 42)")
rec_raw = load_test("20260721_emprefit", "emp")
rec_cal = load_recal("20260721_emprefit", "emp")
L("| ds | bb | raw CRPS | recal CRPS | raw cov | recal cov | raw winkler | recal winkler |")
L("|---|---|--|--|--|--|--|--|")
for key in sorted(set(rec_raw) & set(rec_cal)):
    for s in sorted(set(rec_raw[key]) & set(rec_cal[key])):
        r, c = rec_raw[key][s], rec_cal[key][s]
        L(f"| {key[0]} | {key[1]} | {r['crps']:.4f} | {c['crps']:.4f} | "
          f"{r['coverage']:.3f} | {c['coverage']:.3f} | {r['winkler']:.2f} | {c['winkler']:.2f} |")

# -------------------------------------------------------- val-only ablations
L("")
L("## 6. Validation-only arms (no test evals on disk)")
for arm, note in [("ddpm", "variance-preserving DDPM corruption, fo"),
                  ("ddpm-past", "variance-preserving DDPM corruption, past"),
                  ("emp_w-past", "whitened (per-mode) loss, past"),
                  ("iso-past-ugnet", "996k UGnet denoiser, iso, past"),
                  ("emp-past-ugnet", "996k UGnet denoiser, emp, past"),
                  ("rsh-past-ugnet", "996k UGnet denoiser, rsh, past")]:
    v = load_val("20260721_ladder", arm)
    if not v:
        continue
    L("")
    L(f"### {arm} — {note} (best val sampled CRPS)")
    L("| ds | bb | val CRPS | best epoch | epochs run | seeds |")
    L("|---|---|--|--|--|--|")
    for key in sorted(v):
        cr = [s["crps"] for s in v[key].values() if s["crps"]]
        ep = [s["epoch"] for s in v[key].values() if s["epoch"] is not None]
        ne = [s["n_epochs"] for s in v[key].values()]
        if not cr:
            continue
        L(f"| {key[0]} | {key[1]} | {np.mean(cr):.4f} | {np.mean(ep):.1f} | "
          f"{np.mean(ne):.1f} | {len(cr)} |")

# reference val for the same cells under the shipped config
L("")
L("### reference: shipped 17k GCNN, best val sampled CRPS")
L("| arm | ds | bb | val CRPS | best epoch | epochs run | seeds |")
L("|---|---|---|--|--|--|--|")
for arm in ["iso-past", "emp-past", "iso", "emp"]:
    v = load_val("20260721_ladder", arm)
    for key in sorted(v):
        cr = [s["crps"] for s in v[key].values() if s["crps"]]
        ep = [s["epoch"] for s in v[key].values() if s["epoch"] is not None]
        ne = [s["n_epochs"] for s in v[key].values()]
        if not cr:
            continue
        L(f"| {arm} | {key[0]} | {key[1]} | {np.mean(cr):.4f} | {np.mean(ep):.1f} | "
          f"{np.mean(ne):.1f} | {len(cr)} |")

# ------------------------------------------------------------------ timing
L("")
L("## 7. Sampling wall-time and checkpoint epochs (test evals)")
L("| arm | ds | bb | s/window | gen_seconds | ckpt epoch |")
L("|---|---|---|--|--|--|")
for arm in ["iso-past", "emp-past"]:
    for key, seeds in sorted(load_test("20260721_ladder", arm).items()):
        s = list(seeds.values())[0]
        L(f"| {arm} | {key[0]} | {key[1]} | {s.get('s_per_window')} | "
          f"{s.get('gen_seconds')} | {s.get('ckpt_epoch')} |")

OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT}  ({len(lines)} lines)")
